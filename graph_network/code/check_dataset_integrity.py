import json
from collections import Counter
from pathlib import Path
from typing import Any

import pandas as pd


REQUIRED_EDGE_TYPES = [
    "user_writes_post",
    "user_writes_comment",
    "comment_replies_post",
    "comment_replies_comment",
    "user_comments_on_user_post",
    "user_replies_to_user_comment",
    "user_receives_reply",
]


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
            if isinstance(obj, dict):
                rows.append(obj)
        except Exception:
            rows.append({"_parse_error": line[:200]})
    return rows


def read_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path, low_memory=False)


def is_template_text(text: Any) -> bool:
    lowered = str(text or "").lower()
    return "dry-run" in lowered or "context_reference=" in lowered or "generated by g" in lowered


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", required=True)
    parser.add_argument("--result-dir", required=True)
    parser.add_argument("--expect-live-llm", action="store_true")
    args = parser.parse_args()

    run_dir = Path(args.run_dir).resolve()
    result_dir = Path(args.result_dir).resolve()
    result_dir.mkdir(parents=True, exist_ok=True)

    users = read_csv(run_dir / "users.csv")
    posts = read_csv(run_dir / "posts.csv")
    comments = read_csv(run_dir / "comments.csv")
    profiles = read_csv(run_dir / "persona_profiles.csv")
    edges = read_csv(run_dir / "edges.csv")
    action_trace = read_jsonl(run_dir / "action_trace.jsonl")
    memory_trace = read_jsonl(run_dir / "memory_trace.jsonl")
    events = read_jsonl(run_dir / "events.jsonl")
    llm_trace = read_jsonl(run_dir / "llm_trace.jsonl")
    graph_summary = {}
    graph_summary_path = run_dir / "graph" / "export_summary.json"
    if graph_summary_path.exists():
        graph_summary = json.loads(graph_summary_path.read_text(encoding="utf-8"))

    generated_users = users[users.get("source", pd.Series(dtype=str)).astype(str).eq("generated_bot")] if not users.empty else pd.DataFrame()
    generated_posts = posts[posts.get("is_generated", pd.Series(dtype=str)).astype(str).str.lower().eq("true")] if not posts.empty else pd.DataFrame()
    generated_comments = comments[comments.get("is_generated", pd.Series(dtype=str)).astype(str).str.lower().eq("true")] if not comments.empty else pd.DataFrame()
    generated_comments = generated_comments[~generated_comments.get("is_replay_human", pd.Series(dtype=str)).astype(str).str.lower().eq("true")] if not generated_comments.empty else generated_comments

    action_counts = Counter(row.get("action_type", row.get("event_type", "")) for row in action_trace)
    event_counts = Counter(row.get("event_type", "") for row in events)
    llm_status_counts = Counter(row.get("status", "") for row in llm_trace if row.get("llm_call_id"))
    llm_provider_counts = Counter(row.get("provider", "") for row in llm_trace if row.get("llm_call_id"))
    llm_call_rows = [row for row in llm_trace if row.get("llm_call_id")]
    fallback_rows = [row for row in llm_call_rows if row.get("status") == "fallback"]
    fallback_rate = len(fallback_rows) / max(1, len(llm_call_rows))

    post_template_count = int(generated_posts.get("title", pd.Series(dtype=str)).map(is_template_text).sum() + generated_posts.get("body", pd.Series(dtype=str)).map(is_template_text).sum()) if not generated_posts.empty else 0
    comment_template_count = int(generated_comments.get("body", pd.Series(dtype=str)).map(is_template_text).sum()) if not generated_comments.empty else 0
    empty_comment_count = int(generated_comments.get("body", pd.Series(dtype=str)).fillna("").astype(str).str.strip().eq("").sum()) if not generated_comments.empty else 0
    json_residue_count = int(generated_comments.get("body", pd.Series(dtype=str)).fillna("").astype(str).str.contains(r"```|\\{\\s*\"text\"", regex=True).sum()) if not generated_comments.empty else 0

    edge_type_counts = graph_summary.get("edge_type_counts") or (edges["edge_type"].value_counts().to_dict() if not edges.empty and "edge_type" in edges else {})
    required_edges_present = {edge_type: int(edge_type_counts.get(edge_type, 0)) > 0 for edge_type in REQUIRED_EDGE_TYPES}
    revisit_present = int(edge_type_counts.get("user_revisits_thread", 0)) > 0

    checks = {
        "profiles_match_generated_users": int(profiles["user_id"].nunique()) == len(generated_users) if not profiles.empty else False,
        "has_post_action": action_counts.get("post", 0) > 0,
        "has_comment1_action": action_counts.get("comment1", 0) > 0,
        "has_comment2_action": action_counts.get("comment2", 0) > 0,
        "has_revisit_action": action_counts.get("revisit", 0) > 0,
        "has_skip_action": action_counts.get("skip", 0) > 0,
        "has_notification_created": event_counts.get("notification_created", 0) > 0,
        "has_memory_browse_context": any(row.get("memory_type") == "browse_context" for row in memory_trace),
        "has_memory_post_action_state": any(row.get("memory_type") == "post_action_state" for row in memory_trace),
        "required_edges_present": all(required_edges_present.values()),
        "live_llm_calls_present": bool(llm_call_rows) if args.expect_live_llm else True,
        "live_llm_has_openai": llm_provider_counts.get("openai", 0) > 0 if args.expect_live_llm else True,
        "live_llm_has_gemini": llm_provider_counts.get("gemini", 0) > 0 if args.expect_live_llm else True,
        "fallback_rate_under_20pct": fallback_rate <= 0.20 if args.expect_live_llm else True,
        "no_template_posts": post_template_count == 0 if args.expect_live_llm else True,
        "no_template_comments": comment_template_count == 0 if args.expect_live_llm else True,
        "no_empty_comments": empty_comment_count == 0,
        "no_json_residue_comments": json_residue_count == 0,
    }

    summary = {
        "run_dir": str(run_dir),
        "result_dir": str(result_dir),
        "expect_live_llm": args.expect_live_llm,
        "generated_user_count": int(len(generated_users)),
        "profile_count": int(len(profiles)),
        "unique_profile_users": int(profiles["user_id"].nunique()) if not profiles.empty and "user_id" in profiles else 0,
        "generated_post_count": int(len(generated_posts)),
        "generated_comment_count": int(len(generated_comments)),
        "action_counts": dict(action_counts),
        "event_counts": dict(event_counts),
        "memory_rows": len(memory_trace),
        "llm_call_count": len(llm_call_rows),
        "llm_status_counts": dict(llm_status_counts),
        "llm_provider_counts": dict(llm_provider_counts),
        "llm_fallback_rate": fallback_rate,
        "post_template_count": post_template_count,
        "comment_template_count": comment_template_count,
        "empty_comment_count": empty_comment_count,
        "json_residue_comment_count": json_residue_count,
        "edge_type_counts": edge_type_counts,
        "required_edges_present": required_edges_present,
        "user_revisits_thread_present": revisit_present,
        "checks": checks,
        "passed": all(checks.values()),
    }
    (result_dir / "dataset_integrity_summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [
        "# graph_network完整性检查报告",
        "",
        f"- run_dir: `{run_dir}`",
        f"- generated users: `{summary['generated_user_count']}`",
        f"- profiles: `{summary['profile_count']}`",
        f"- generated posts: `{summary['generated_post_count']}`",
        f"- generated comments: `{summary['generated_comment_count']}`",
        f"- llm calls: `{summary['llm_call_count']}`",
        f"- llm fallback rate: `{fallback_rate:.2%}`",
        "",
        "## Action 分布",
        "",
        pd.Series(dict(action_counts), dtype="object").to_markdown(),
        "",
        "## LLM Provider 分布",
        "",
        pd.Series(dict(llm_provider_counts), dtype="object").to_markdown() if llm_provider_counts else "无 LLM 调用。",
        "",
        "## 图边检查",
        "",
        pd.Series(edge_type_counts, dtype="object").to_markdown(),
        "",
        "## 验收项",
        "",
        pd.Series(checks, dtype="object").to_markdown(),
        "",
        f"总体结论：`{'PASS' if summary['passed'] else 'FAIL'}`",
    ]
    (result_dir / "dataset_integrity_report_cn.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
